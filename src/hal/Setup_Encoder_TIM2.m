'#elif defined(TARGET_NUCLEO_F401RE)' newline ...
'#include "stm32f401xe.h"' newline ...
'#elif defined(TARGET_NUCLEO_F411RE)' newline ...
'#include "stm32f411xe.h"' newline ...
'#else' newline ...
'#error "Encoder supported with STM32 Nucleo-F767ZI, STM32 Nucleo-F401RE or STM32 Nucleo-F411RE boards."' newline ...
'#endif' newline ...
'' newline ...
'void initEncoder_TIM2(void)' newline ...
'{' newline ...
'    // 1. Bat Clock cho GPIOA (Bit 0) va GPIOB (Bit 1) tren AHB1ENR' newline ...
'    RCC->AHB1ENR |= 0x00000003;' newline ...
'' newline ...
'    // 2. Cau hinh PA15 (TIM2_CH1 - AF1)' newline ...
'    GPIOA->MODER   &= ~(GPIO_MODER_MODER15);' newline ...
'    GPIOA->PUPDR   &= ~(GPIO_PUPDR_PUPDR15);' newline ...
'    GPIOA->AFR[1]  &= ~(0xF0000000);' newline ...
'    GPIOA->MODER   |= (GPIO_MODER_MODER15_1);          // Alternate Function' newline ...
'    GPIOA->OTYPER  |= (GPIO_OTYPER_OT_15);' newline ...
'    GPIOA->OSPEEDR |= (GPIO_OSPEEDER_OSPEEDR15);' newline ...
'    GPIOA->PUPDR   |= (GPIO_PUPDR_PUPDR15_0);          // Pull-up 3.3V' newline ...
'    GPIOA->AFR[1]  |= 0x10000000;                      // AF1 = TIM2_CH1 tren PA15' newline ...
'' newline ...
'    // 3. Cau hinh PB3 (TIM2_CH2 - AF1)' newline ...
'    GPIOB->MODER   &= ~(GPIO_MODER_MODER3);' newline ...
'    GPIOB->PUPDR   &= ~(GPIO_PUPDR_PUPDR3);' newline ...
'    GPIOB->AFR[0]  &= ~(0x0000F000);' newline ...
'    GPIOB->MODER   |= (GPIO_MODER_MODER3_1);           // Alternate Function' newline ...
'    GPIOB->OTYPER  |= (GPIO_OTYPER_OT_3);' newline ...
'    GPIOB->OSPEEDR |= (GPIO_OSPEEDER_OSPEEDR3);' newline ...
'    GPIOB->PUPDR   |= (GPIO_PUPDR_PUPDR3_0);           // Pull-up 3.3V' newline ...
'    GPIOB->AFR[0]  |= 0x00001000;                      // AF1 = TIM2_CH2 tren PB3' newline ...
'' newline ...
'    // 4. Bat Clock cho TIM2 (Bit 0 cua APB1ENR)' newline ...
'    RCC->APB1ENR   |= 0x00000001;' newline ...
'' newline ...
'    // 5. Cau hinh TIM2 chay Encoder Mode 3 (Dem 4x, gioi han 16-bit 0->65535)' newline ...
'    TIM2->CR1   = 0x0000;' newline ...
'    TIM2->SMCR  = 0x0003;     // SMS = 011 (Encoder mode 3)' newline ...
'    TIM2->CCMR1 = 0x0101;     // CC1S = 01, CC2S = 01' newline ...
'    TIM2->CCMR2 = 0x0000;' newline ...
'    TIM2->CCER  = 0x0011;     // CC1P, CC2P enable' newline ...
'    TIM2->PSC   = 0x0000;     // Prescaler = 0' newline ...
'    TIM2->ARR   = 0xFFFF;     // Ep ve 16-bit (65535) de dung chung bo unwrap voi TIM3' newline ...
'    TIM2->CNT   = 0x0000;     // Reset counter' newline ...
'    TIM2->CR1   = 0x0001;     // Enable counter (CEN = 1)' newline ...
'}' newline ...
'' newline ...
'unsigned short int getEncoderCount_TIM2(void)' newline ...
'{' newline ...
'    return (unsigned short int)(TIM2->CNT & 0xFFFF);' newline ...
'}' newline ...
'' newline ...
'unsigned short int getIndexCount_TIM2(unsigned short int *indexCount)' newline ...
'{' newline ...
'    *indexCount = 0;' newline ...
'    return 0;' newline ...
'}' newline ...
'' newline ...
'void releaseEncoder_TIM2(void)' newline ...
'{' newline ...
'    TIM2->CR1 = 0x0000;' newline ...
'}' newline ...
];

