% =========================================================================
% KICH BAN KHOI TAO KHOI ENCODER TIM2 TREN CHAN PA15 VA PB3
% =========================================================================

clc;
fprintf('Dang khoi tao khoi EncoderBlock_TIM2...\n');

if ~exist('include', 'dir')
    mkdir('include');
end
if ~exist('src', 'dir')
    mkdir('src');
end

h_content = [
'#ifndef SOC_STM_ENCODER_TIM2_H' newline ...
'#define SOC_STM_ENCODER_TIM2_H' newline ...
'' newline ...
'#ifdef __cplusplus' newline ...
'extern "C" {' newline ...
'#endif' newline ...
'' newline ...
'void initEncoder_TIM2(void);' newline ...
'unsigned short int getEncoderCount_TIM2(void);' newline ...
'unsigned short int getIndexCount_TIM2(unsigned short int *indexCount);' newline ...
'void releaseEncoder_TIM2(void);' newline ...
'' newline ...
'#ifdef __cplusplus' newline ...
'}' newline ...
'#endif' newline ...
'' newline ...
'#endif' newline ...
];

fid_h = fopen(fullfile('include', 'soc_stm_encoder_tim2.h'), 'w');
fwrite(fid_h, h_content);
fclose(fid_h);

cpp_content = [
'#include "soc_stm_encoder_tim2.h"' newline ...
'#include "mw_mbed_interface.h"' newline ...
'#if defined(TARGET_NUCLEO_F411RE) || defined(TARGET_NUCLEO_F401RE)' newline ...
'#include "stm32f411xe.h"' newline ...
'#endif' newline ...
'' newline ...
'void initEncoder_TIM2(void)' newline ...
'{' newline ...
'    RCC->AHB1ENR |= 0x00000003;' newline ...
'    GPIOA->MODER   &= ~GPIO_MODER_MODER15;' newline ...
'    GPIOA->PUPDR   &= ~GPIO_PUPDR_PUPDR15;' newline ...
'    GPIOA->AFR[1]  &= ~0xF0000000;' newline ...
'    GPIOA->MODER   |= GPIO_MODER_MODER15_1;' newline ...
'    GPIOA->OTYPER  |= GPIO_OTYPER_OT_15;' newline ...
'    GPIOA->OSPEEDR |= GPIO_OSPEEDER_OSPEEDR15;' newline ...
'    GPIOA->PUPDR   |= GPIO_PUPDR_PUPDR15_0;' newline ...
'    GPIOA->AFR[1]  |= 0x10000000;' newline ...
'' newline ...
'    GPIOB->MODER   &= ~GPIO_MODER_MODER3;' newline ...
'    GPIOB->PUPDR   &= ~GPIO_PUPDR_PUPDR3;' newline ...
'    GPIOB->AFR[0]  &= ~0x0000F000;' newline ...
'    GPIOB->MODER   |= GPIO_MODER_MODER3_1;' newline ...
'    GPIOB->OTYPER  |= GPIO_OTYPER_OT_3;' newline ...
'    GPIOB->OSPEEDR |= GPIO_OSPEEDER_OSPEEDR3;' newline ...
'    GPIOB->PUPDR   |= GPIO_PUPDR_PUPDR3_0;' newline ...
'    GPIOB->AFR[0]  |= 0x00001000;' newline ...
'' newline ...
'    RCC->APB1ENR |= 0x00000001;' newline ...
'    TIM2->CR1   = 0x0000;' newline ...
'    TIM2->SMCR  = 0x0003;' newline ...
'    TIM2->CCMR1 = 0x0101;' newline ...
'    TIM2->CCMR2 = 0x0000;' newline ...
'    TIM2->CCER  = 0x0011;' newline ...
'    TIM2->PSC   = 0x0000;' newline ...
'    TIM2->ARR   = 0xFFFF;' newline ...
'    TIM2->CNT   = 0x0000;' newline ...
'    TIM2->CR1   = 0x0001;' newline ...
'}' newline ...
'' newline ...
'unsigned short int getEncoderCount_TIM2(void)' newline ...
'{' newline ...
'    return (unsigned short int)(TIM2->CNT & 0xFFFF);' newline ...
'}' newline ...
'' newline ...
'unsigned short int getIndexCount_TIM2(unsigned short int *indexCount)' newline ...
'{' newline ...
'    *indexCount = 0;' newline ...
'    return 0;' newline ...
'}' newline ...
'' newline ...
'void releaseEncoder_TIM2(void)' newline ...
'{' newline ...
'    TIM2->CR1 = 0x0000;' newline ...
'}' newline ...
];

fid_cpp = fopen(fullfile('src', 'soc_stm_encoder_tim2.cpp'), 'w');
fwrite(fid_cpp, cpp_content);
fclose(fid_cpp);

fprintf('Hoan tat khoi tao ma nguon ngoai vi TIM2.\n');
