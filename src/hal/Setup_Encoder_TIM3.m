'    TIM3->CCMR1 = 0x0101;     // CC1S = 01, CC2S = 01' newline ...
'    TIM3->CCMR2 = 0x0000;' newline ...
'    TIM3->CCER  = 0x0011;     // CC1P, CC2P enable' newline ...
'    TIM3->PSC   = 0x0000;     // Prescaler = 0' newline ...
'    TIM3->ARR   = 0xFFFF;     // 16-bit full range (0 -> 65535)' newline ...
'    TIM3->CNT   = 0x0000;     // Reset counter' newline ...
