'    GPIOA->MODER   |= (GPIO_MODER_MODER6_1 | GPIO_MODER_MODER7_1);' newline ...
'    GPIOA->OTYPER  |= (GPIO_OTYPER_OT_6 | GPIO_OTYPER_OT_7);' newline ...
