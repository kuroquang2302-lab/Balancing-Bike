% =========================================================================
% SETUP SCRIPT FOR HARDWARE ENCODER TIM3 ON PINS PA6 AND PA7
% =========================================================================

clc;
fprintf('Initializing EncoderBlock_TIM3 driver source files...\n');

if ~exist('include', 'dir')
    mkdir('include');
end
if ~exist('src', 'dir')
    mkdir('src');
end

h_content = [
'#ifndef SOC_STM_ENCODER_TIM3_H' newline ...
'#define SOC_STM_ENCODER_TIM3_H' newline ...
'' newline ...
'#ifdef __cplusplus' newline ...
'extern "C" {' newline ...
'#endif' newline ...
'' newline ...
'void initEncoder_TIM3(void);' newline ...
'unsigned short int getEncoderCount_TIM3(void);' newline ...
'unsigned short int getIndexCount_TIM3(unsigned short int *indexCount);' newline ...
'void releaseEncoder_TIM3(void);' newline ...
'' newline ...
'#ifdef __cplusplus' newline ...
'}' newline ...
'#endif' newline ...
'' newline ...
'#endif' newline ...
];

fid_h = fopen(fullfile('include', 'soc_stm_encoder_tim3.h'), 'w');
fwrite(fid_h, h_content);
fclose(fid_h);

cpp_content = [
'#include "soc_stm_encoder_tim3.h"' newline ...
'#include "mw_mbed_interface.h"' newline ...
'#if defined(TARGET_NUCLEO_F411RE) || defined(TARGET_NUCLEO_F401RE)' newline ...
'#include "stm32f411xe.h"' newline ...
'#endif' newline ...
'' newline ...
'void initEncoder_TIM3(void)' newline ...
'{' newline ...
'    RCC->AHB1ENR |= 0x00000001;' newline ...
'    GPIOA->MODER   &= ~(GPIO_MODER_MODER6 | GPIO_MODER_MODER7);' newline ...
'    GPIOA->PUPDR   &= ~(GPIO_PUPDR_PUPDR6 | GPIO_PUPDR_PUPDR7);' newline ...
'    GPIOA->AFR[0]  &= ~0xFF000000;' newline ...
'    GPIOA->MODER   |= GPIO_MODER_MODER6_1 | GPIO_MODER_MODER7_1;' newline ...
'    GPIOA->OTYPER  |= GPIO_OTYPER_OT_6 | GPIO_OTYPER_OT_7;' newline ...
'    GPIOA->OSPEEDR |= GPIO_OSPEEDER_OSPEEDR6 | GPIO_OSPEEDER_OSPEEDR7;' newline ...
'    GPIOA->PUPDR   |= GPIO_PUPDR_PUPDR6_0 | GPIO_PUPDR_PUPDR7_0;' newline ...
'    GPIOA->AFR[0]  |= 0x22000000;' newline ...
'    RCC->APB1ENR   |= 0x00000002;' newline ...
'    TIM3->CR1   = 0x0000;' newline ...
'    TIM3->SMCR  = 0x0003;' newline ...
'    TIM3->CCMR1 = 0x0101;' newline ...
'    TIM3->CCMR2 = 0x0000;' newline ...
'    TIM3->CCER  = 0x0011;' newline ...
'    TIM3->PSC   = 0x0000;' newline ...
'    TIM3->ARR   = 0xFFFF;' newline ...
'    TIM3->CNT   = 0x0000;' newline ...
'    TIM3->CR1   = 0x0001;' newline ...
'}' newline ...
'' newline ...
'unsigned short int getEncoderCount_TIM3(void)' newline ...
'{' newline ...
'    return (unsigned short int)(TIM3->CNT & 0xFFFF);' newline ...
'}' newline ...
'' newline ...
'unsigned short int getIndexCount_TIM3(unsigned short int *indexCount)' newline ...
'{' newline ...
'    *indexCount = 0;' newline ...
'    return 0;' newline ...
'}' newline ...
'' newline ...
'void releaseEncoder_TIM3(void)' newline ...
'{' newline ...
'    TIM3->CR1 = 0x0000;' newline ...
'}' newline ...
];

fid_cpp = fopen(fullfile('src', 'soc_stm_encoder_tim3.cpp'), 'w');
fwrite(fid_cpp, cpp_content);
fclose(fid_cpp);

fprintf('Completed TIM3 peripheral driver setup.\n');
